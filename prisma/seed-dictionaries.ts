async function main() {
  console.log('🌱 Start seeding dictionaries...');

  // Seed Professions
  console.log(`Processing ${commonProfessions.length} professions...`);
  for (const name of commonProfessions) {
    await prisma.profession.upsert({
      where: { name },
      update: {},
      create: { name },
    });
  }

  // Seed Job Titles
  console.log(`Processing ${commonJobTitles.length} job titles...`);
  for (const name of commonJobTitles) {
    await prisma.jobTitle.upsert({
      where: { name },
      update: {},
      create: { name },
    });
  }

  console.log('✅ Seeding completed.');
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });

