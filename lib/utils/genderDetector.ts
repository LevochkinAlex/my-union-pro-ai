/**
 * Определяет пол ребенка по имени
 * Возвращает "М" (мальчик) или "Ж" (девочка)
 */
export function detectGenderByName(name: string): "М" | "Ж" {
  if (!name || name.trim() === "") {
    return "М"; // По умолчанию мальчик
  }

  const lowerName = name.trim().toLowerCase();

  // Женские окончания
  const femaleEndings = [
    "а", "я", "ия", "ья", "на", "ина", "ана", "ена", "ида", "есса",
    "етта", "елла", "илла", "исса", "она", "юля", "оля",
  ];

  // Женские имена-исключения (не заканчиваются на типичные окончания)
  const femaleNames = [
    "любовь", "эстер", "рахиль", "юдифь", "мирьям", "кармен", "долорес",
    "мерседес", "консепсьон", "соледад", "инес", "беатрис", "элис", "элизабет",
  ];

  // Мужские имена на -а/-я (исключения)
  const maleNamesOnA = [
    "никита", "илья", "лука", "кузьма", "фома", "савва", "аникита",
    "данила", "мина", "сила", "ермил", "кирила", "мефодия", "захария",
    "муса", "иса", "сулейман", "яша", "миша", "саша", "жора", "коля",
    "вася", "дима", "гоша", "алеша", "лёша", "паша", "гриша", "андрюша",
  ];

  // Проверяем мужские имена-исключения
  if (maleNamesOnA.includes(lowerName)) {
    return "М";
  }

  // Проверяем женские имена-исключения
  if (femaleNames.includes(lowerName)) {
    return "Ж";
  }

  // Проверяем по окончаниям
  for (const ending of femaleEndings) {
    if (lowerName.endsWith(ending)) {
      return "Ж";
    }
  }

  // По умолчанию - мальчик
  return "М";
}

