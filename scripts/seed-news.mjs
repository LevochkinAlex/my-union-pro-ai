async function seedNews() {
  try {
    console.log('🌱 Начинаем загрузку новостей...');
    
    // Находим супер-админа
    const superAdmin = await prisma.user.findFirst({
      where: {
        role: 'SUPER_ADMIN'
      }
    });

    if (!superAdmin) {
      console.error('❌ Супер-админ не найден! Создайте супер-админа перед загрузкой новостей.');
      process.exit(1);
    }

    console.log(`✅ Найден супер-админ: ${superAdmin.email}`);

    // Создаем новости
    for (const [index, news] of newsData.entries()) {
      const createdNews = await prisma.newsPost.create({
        data: {
          ...news,
          authorId: superAdmin.id,
          publishedAt: news.isPublished ? new Date() : null,
        }
      });
      
      console.log(`✅ Создана новость ${index + 1}/${newsData.length}: "${createdNews.title}"`);
    }

    console.log('\n🎉 Все новости успешно загружены!');
    console.log(`📰 Загружено новостей: ${newsData.length}`);
    
  } catch (error) {
    console.error('❌ Ошибка при загрузке новостей:', error);
    process.exit(1);
  } finally {
    await prisma.$disconnect();
  }
}

seedNews();

