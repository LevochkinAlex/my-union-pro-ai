async function main() {
  console.log("🚀 Создаём структуру Московской областной организации...\n");

  try {
    // Удаляем старые организации
    const existingCount = await prisma.organization.count();
    if (existingCount > 0) {
      console.log(`⚠️  Удаляем ${existingCount} старых организаций...`);
      await prisma.organization.deleteMany({});
      console.log("✅ Старые организации удалены\n");
    }

    // 1. Создаём региональную организацию
    const regional = await prisma.organization.create({
      data: {
        name: "Московская областная организация профсоюза работников здравоохранения РФ",
        type: "REGIONAL",
        inn: "5000000001",
        address: "Московская область",
        isActive: true,
      },
    });
    console.log("✅ Создана региональная организация:");
    console.log(`   ${regional.name}\n`);

    // 2. Создаём местные организации
    console.log(`📋 Создаём ${localOrganizations.length} местных организаций...\n`);
    
    const localOrgMap = new Map<string, string>(); // название -> id
    
    for (let i = 0; i < localOrganizations.length; i++) {
      const name = localOrganizations[i];
      const org = await prisma.organization.create({
        data: {
          name,
          type: "REGIONAL", // Местные тоже региональные по типу
          parentId: regional.id,
          isActive: true,
        },
      });
      localOrgMap.set(name, org.id);
      
      if ((i + 1) % 10 === 0 || i === localOrganizations.length - 1) {
        console.log(`   ✓ Создано ${i + 1}/${localOrganizations.length} местных организаций`);
      }
    }

    // 3. Создаём ППО
    console.log(`\n📋 Создаём ${primaryOrganizations.length} первичных организаций (ППО)...\n`);
    
    for (let i = 0; i < primaryOrganizations.length; i++) {
      const name = primaryOrganizations[i];
      
      // Определяем родительскую организацию по названию
      let parentId = regional.id; // По умолчанию напрямую к региональной
      
      // Пытаемся найти местную организацию по ключевому слову
      const cityMatch = name.match(/"([А-Яа-яё-]+)/);
      if (cityMatch) {
        const cityName = cityMatch[1];
        // Ищем соответствующую местную организацию
        for (const [localName, localId] of localOrgMap) {
          if (localName.toLowerCase().includes(cityName.toLowerCase().slice(0, 5))) {
            parentId = localId;
            break;
          }
        }
      }
      
      await prisma.organization.create({
        data: {
          name,
          type: "PRIMARY",
          parentId,
          isActive: true,
        },
      });
      
      if ((i + 1) % 20 === 0 || i === primaryOrganizations.length - 1) {
        console.log(`   ✓ Создано ${i + 1}/${primaryOrganizations.length} ППО`);
      }
    }

    // Статистика
    const stats = await prisma.organization.groupBy({
      by: ["type"],
      _count: true,
    });

    const total = await prisma.organization.count();
    const primaryCount = await prisma.organization.count({ where: { type: "PRIMARY" } });

    console.log("\n📊 Итоговая статистика:");
    console.log(`   Всего организаций: ${total}`);
    stats.forEach((item) => {
      const typeName = 
        item.type === "FEDERATION" ? "Федеральных" :
        item.type === "REGIONAL" ? "Региональных/Местных" :
        "Первичных (ППО)";
      console.log(`   ${typeName}: ${item._count}`);
    });

    console.log("\n✅ Структура успешно создана!");
    console.log(`\n💡 В анкете теперь доступно ${primaryCount} ППО для выбора`);
    console.log("🔗 Иерархия: Региональная → Местные → ППО\n");
  } catch (error: any) {
    console.error("\n❌ Ошибка:", error.message);
    throw error;
  } finally {
    await prisma.$disconnect();
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});

