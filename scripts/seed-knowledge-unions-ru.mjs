async function yandexDocEmbedding(text) {
  const response = await fetch(
    "https://llm.api.cloud.yandex.net/foundationModels/v1/textEmbedding",
    {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Api-Key ${API_KEY}`,
      },
      body: JSON.stringify({
        modelUri: `emb://${FOLDER_ID}/text-search-doc/latest`,
        text,
      }),
    },
  );
  if (!response.ok) {
    const t = await response.text();
    throw new Error(`Yandex embedding ${response.status}: ${t.slice(0, 200)}`);
  }
  const data = await response.json();
  if (!Array.isArray(data.embedding)) {
    throw new Error("Yandex embedding: пустой ответ");
  }
  return data.embedding;
}

function splitIntoChunks(text, chunkSize = 400, overlap = 60) {
  const clean = text.replace(/\r\n/g, "\n").trim();
  if (clean.length <= chunkSize) return [clean];
  const chunks = [];
  let start = 0;
  while (start < clean.length) {
    const end = Math.min(start + chunkSize, clean.length);
    chunks.push(clean.slice(start, end).trim());
    if (end === clean.length) break;
    start = end - overlap;
  }
  return chunks.filter((c) => c.length > 30);
}

