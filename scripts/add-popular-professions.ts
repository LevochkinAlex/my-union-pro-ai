async function addPopularProfessions() {
  console.log("\n📚 ДОБАВЛЕНИЕ ПОПУЛЯРНЫХ ПРОФЕССИЙ В СПРАВОЧНИК\n");
  console.log("═".repeat(70));
  
  let added = 0;
  let skipped = 0;
  const errors: string[] = [];

  for (const professionName of POPULAR_PROFESSIONS) {
    try {
      // Проверяем, существует ли уже
      const existing = await prisma.profession.findFirst({
        where: { 
          name: { 
            equals: professionName, 
            mode: "insensitive" 
          } 
        },
      });

      if (!existing) {
        await prisma.profession.create({ 
          data: { name: professionName } 
        });
        console.log(`✅ Добавлено: ${professionName}`);
        added++;
      } else {
        console.log(`⏭️  Пропущено (уже существует): ${professionName}`);
        skipped++;
      }
    } catch (error: any) {
      const errorMsg = `❌ Ошибка при добавлении "${professionName}": ${error.message}`;
      console.error(errorMsg);
      errors.push(errorMsg);
    }
  }

  console.log("\n" + "═".repeat(70));
  console.log("📊 ИТОГИ:");
  console.log(`   ✅ Добавлено: ${added}`);
  console.log(`   ⏭️  Пропущено: ${skipped}`);
  console.log(`   ❌ Ошибок: ${errors.length}`);
  
  if (errors.length > 0) {
    console.log("\n❌ ОШИБКИ:");
    errors.forEach(err => console.log(`   ${err}`));
  }

  const totalProfessions = await prisma.profession.count();
  console.log(`\n📚 Всего профессий в справочнике: ${totalProfessions}`);
  console.log("═".repeat(70) + "\n");
}

addPopularProfessions()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error("Fatal error:", error);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());

