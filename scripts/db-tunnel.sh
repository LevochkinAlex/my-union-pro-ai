#!/bin/bash

# SSH туннель для подключения локального dev-сервера к продакшн БД
# Запускайте в отдельном терминале перед npm run dev

echo "🔌 Создание SSH туннеля к продакшн БД..."
echo "📍 Локальный порт: 5432 → Удаленный: 5432"
echo ""
echo "⚠️  Не закрывайте это окно терминала!"
echo "Для остановки нажмите Ctrl+C"
echo ""

ssh -i ~/.ssh/myunion_vds \
  -L 5432:localhost:5432 \
  -N \
  root@194.87.49.210

echo ""
echo "❌ Туннель закрыт"

