#!/bin/bash
# Скрипт для полного деплоя с миграциями каналов

set -e

echo "🚀 Начинаем деплой с миграциями..."

# Переходим в директорию проекта
cd /opt/my-union-pro

# 1. Обновляем код
echo "📥 Обновляем код из репозитория..."
git pull origin main

# 2. Применяем миграции каналов
echo "🔧 Применяем миграции для каналов..."
bash scripts/apply-channel-migrations.sh

# 3. Собираем проект
echo "🔨 Собираем проект..."
rm -rf .next
pnpm build

# 4. Перезапускаем приложение
echo "🔄 Перезапускаем приложение..."
pm2 restart my-union-pro

# 5. Проверяем статус
echo "✅ Проверяем статус..."
sleep 5
pm2 status | head -5

echo "✅ Деплой с миграциями завершен успешно!"
